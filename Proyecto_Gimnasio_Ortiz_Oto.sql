-- 5. Administración y seguridad
--CREAMOS ROLES
CREATE ROLE rol_administrador;
CREATE ROLE rol_recepcionista;
CREATE ROLE rol_entrenador;
CREATE ROLE rol_nutricionista;
CREATE ROLE rol_cliente;

-- ROL ADMINISTRADOR (acceso completo)
GRANT ALL PRIVILEGES ON DATABASE "Gimnasio_Ortiz_Oto" TO rol_administrador;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO rol_administrador;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO rol_administrador;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO rol_administrador;

-- ROL RECEPCIONISTA (gestión de clientes, membresías, pagos)
GRANT SELECT, INSERT, UPDATE ON cliente TO rol_recepcionista;
GRANT SELECT ON membresia TO rol_recepcionista;
GRANT SELECT, INSERT, UPDATE ON inscripcion_membresia TO rol_recepcionista;
GRANT SELECT, INSERT ON factura TO rol_recepcionista;
GRANT SELECT, INSERT ON pago TO rol_recepcionista;
GRANT SELECT ON rutina TO rol_recepcionista;
GRANT SELECT ON entrenador TO rol_recepcionista;
GRANT SELECT ON nutricionista TO rol_recepcionista;

-- ROL ENTRENADOR (gestión de rutinas y ejercicios)
GRANT SELECT ON cliente TO rol_entrenador;
GRANT SELECT, INSERT, UPDATE, DELETE ON rutina TO rol_entrenador;
GRANT SELECT, INSERT, UPDATE, DELETE ON rutina_ejercicio TO rol_entrenador;
GRANT SELECT ON ejercicio TO rol_entrenador;
GRANT SELECT ON entrenador TO rol_entrenador;

-- ROL NUTRICIONISTA (gestión de evaluaciones y dietas)
GRANT SELECT ON cliente TO rol_nutricionista;
GRANT SELECT, INSERT, UPDATE ON evaluacion_nutricional TO rol_nutricionista;
